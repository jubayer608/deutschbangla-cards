import { words, type Difficulty } from "./words";

export type ExerciseType = "mcq" | "fillblank" | "translate" | "order";

export interface Exercise {
  type: ExerciseType;
  difficulty: Difficulty;
  prompt: string;
  promptBangla?: string;
  options?: string[];
  answer: string;
  explanation: string;
}

export interface GrammarBlock {
  title: string;
  explanation: string;
  table?: { headers: string[]; rows: string[][] };
  examples?: { german: string; bangla: string }[];
}

// Exam-Fragenbank: jede Lesson hat genau 10 Fragen für die zeitgesteuerte
// Abschlussprüfung (nächster Schritt: Exam-UI mit 5-Minuten-Timer, Bestehen ab 70 %).
// `exam` benutzt denselben `Exercise`-Typ wie `uebungen` (mcq | fillblank |
// translate | order; mcq/order brauchen `options`, alle Fragen eine Bangla-
// `explanation`). Die Fragen testen nur Inhalte der jeweiligen Lesson.
export interface Lesson {
  id: number;
  slug: string;
  title: string;
  titleBangla: string;
  ziele: string[];
  vocabIds: string[];
  grammar: GrammarBlock[];
  saetze: { german: string; bangla: string }[];
  uebungen: Exercise[];
  exam?: Exercise[];
}

// Robust vocabulary id lookup: "<categoryId>-<NN>", first n words of a category.
export const v = (cat: string, n: number): string[] =>
  words.filter(w => w.category === cat).slice(0, n).map(w => w.id);

